-- Artha Banking managment
-- Sql Commands to create the required database structure

CREATE DATABASE IF NOT EXISTS ARTHA;
USE ARTHA;

CREATE TABLE ROLE(
    ROLE_ID      INT             NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    ROLE_NAME    VARCHAR(50)     NOT NULL  UNIQUE
);

CREATE TABLE ACCOUNT_TYPE(
    AC_TYPE         INT             NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    AC_TYPE_NAME    VARCHAR(50)     NOT NULL  UNIQUE
);

CREATE TABLE INVESTMENT_TYPE(
    INVEST_TYPE      INT             NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    INVEST_NAME      VARCHAR(50)     NOT NULL  UNIQUE 
);

CREATE TABLE INVESTMENT_SCHEME(
    INVESTMENT_SCHEME_ID    INT             NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    INVEST_TYPE             INT             NOT NULL,
    SCHEME_NAME             VARCHAR(100)    NOT NULL  UNIQUE,
    DURATION_OF_MONTHS      INT             NOT NULL,
    INTEREST_RATE           DECIMAL(5,4)    NOT NULL,

    CONSTRAINT FK_INVESTSCHEME_INVESTTYPE 
        FOREIGN KEY(INVEST_TYPE)
        REFERENCES INVESTMENT_TYPE(INVEST_TYPE)
);

CREATE TABLE TRANSACTION_CODE(
    TRANS_CODE   INT             NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    TRANS_NAME   VARCHAR(50)     NOT NULL  UNIQUE
);

CREATE TABLE REQUEST_TYPE(
    REQUEST_CODE   INT             NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    REQUEST_NAME   VARCHAR(50)     NOT NULL  UNIQUE
);

CREATE TABLE HARDWARE_TYPE(
    HARDWARE_CODE    INT         NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    HARDWARE_NAME    VARCHAR(50) NOT NULL  UNIQUE,
    CRITICAL         BOOLEAN     NOT NULL  
);

CREATE TABLE USER(
    USER_ID         INT             NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    NAME            VARCHAR(50)     NOT NULL,
    DOB             DATE            NOT NULL,
    GENDER          VARCHAR(10)     NOT NULL,
    EMAIL           VARCHAR(100)    NOT NULL  UNIQUE,
    MOBILE_NUMBER   VARCHAR(12)     NOT NULL  UNIQUE,
    ADDRESS         VARCHAR(255)    NOT NULL,
    AADHAR_NUMBER   VARCHAR(12)     NOT NULL  UNIQUE,
    PAN_NUMBER      VARCHAR(10)     NOT NULL  UNIQUE,
    STATUS          VARCHAR(25)     NOT NULL  DEFAULT 'NOT VERIFIED'
);

CREATE TABLE USERAUTH(
    USER_ID         INT             NOT NULL  PRIMARY KEY,
    USERNAME        VARCHAR(50)     NOT NULL  UNIQUE,
    PASSWORD_HASH   VARCHAR(255)    NOT NULL,
    LOCK_UNTIL      DATETIME        NULL,  

    CONSTRAINT FK_USERAUTH_USERID
        FOREIGN KEY(USER_ID)
        REFERENCES USER(USER_ID)
);

CREATE TABLE USER_ROLE(
    USER_ID     INT     NOT NULL,
    ROLE_ID     INT     NOT NULL,

    PRIMARY KEY(USER_ID, ROLE_ID),

    CONSTRAINT FK_USERROLE_USERID
        FOREIGN KEY(USER_ID)
        REFERENCES USER(USER_ID),
    
    CONSTRAINT FK_USERROLE_ROLEID
        FOREIGN KEY(ROLE_ID)
        REFERENCES ROLE(ROLE_ID)
);

CREATE TABLE BOOTH(
    BOOTH_ID    INT         PRIMARY KEY  AUTO_INCREMENT,
    STATUS      VARCHAR(50) NOT NULL
);

CREATE TABLE HARDWARE(
    HARDWARE_ID     INT         NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    HARDWARE_CODE   INT         NOT NULL,
    BOOTH_ID        INT         NOT NULL,
    STATUS          VARCHAR(50) NOT NULL,

    CONSTRAINT FK_HARDWARE_HARDWARECODE
        FOREIGN KEY(HARDWARE_CODE)
        REFERENCES HARDWARE_TYPE(HARDWARE_CODE),

    CONSTRAINT FK_HARDWARE_BOOTHID
        FOREIGN KEY(BOOTH_ID)
        REFERENCES BOOTH(BOOTH_ID)
);

CREATE TABLE ACCOUNT(
    AC_NO       VARCHAR(20)     NOT NULL  PRIMARY KEY,
    AC_TYPE     INT             NOT NULL,
    USER_ID     INT             NOT NULL,
    ACBAL       DECIMAL(12,2)   NOT NULL,
    STATUS      VARCHAR(20)     NOT NULL  DEFAULT 'ACTIVE',

    CONSTRAINT FK_ACCOUNT_ACTYPE
        FOREIGN KEY(AC_TYPE)
        REFERENCES ACCOUNT_TYPE(AC_TYPE),

    CONSTRAINT FK_ACCOUNT_USERID
        FOREIGN KEY(USER_ID)
        REFERENCES USER(USER_ID)
);

CREATE TABLE INVESTMENT(
    INVEST_NO               INT             NOT NULL  PRIMARY KEY  AUTO_INCREMENT, 
    INVESTMENT_SCHEME_ID    INT             NOT NULL,
    USER_ID                 INT             NOT NULL,
    INVESTED_AMT            DECIMAL(12,2)   NOT NULL,
    MATURITY_AMT            DECIMAL(12,2)   NOT NULL,
    START_DATE              DATE            NOT NULL,
    END_DATE                DATE            NOT NULL,
    STATUS                  VARCHAR(20)     NOT NULL,

    CONSTRAINT FK_INVESTMENT_INVESTMENTSCHEMEID
        FOREIGN KEY(INVESTMENT_SCHEME_ID)
        REFERENCES INVESTMENT_SCHEME(INVESTMENT_SCHEME_ID),

    CONSTRAINT FK_INVESTMENT_USERID
        FOREIGN KEY(USER_ID)
        REFERENCES USER(USER_ID)

);

CREATE TABLE LOAN(
    LOAN_ID         INT             NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    USER_ID         INT             NOT NULL,
    LOAN_TYPE       VARCHAR(50)     NOT NULL,
    PRINCIPAL_AMT   DECIMAL(12,2)   NOT NULL,
    OUTSTANDING_AMT DECIMAL(12,2)   NOT NULL,
    START_DATE      DATE            NOT NULL,
    END_DATE        DATE            NOT NULL,
    STATUS          VARCHAR(50)     NOT NULL,

    CONSTRAINT FK_LOAN_USERID
        FOREIGN KEY(USER_ID)
        REFERENCES USER(USER_ID)
);

CREATE TABLE LOAN_REPAYMENT(
    REPAYMENT_ID    INT             NOT NULL  AUTO_INCREMENT  PRIMARY KEY,
    LOAN_ID         INT             NOT NULL,
    INSTALLMENT_NUM INT             NOT NULL, 
    DUE_DATE        DATE            NOT NULL,
    AMT             DECIMAL(12,2)   NOT NULL,
    STATUS          VARCHAR(50)     NOT NULL,

    CONSTRAINT FK_LOANREPAYMENT_LOANID
        FOREIGN KEY(LOAN_ID)
        REFERENCES LOAN(LOAN_ID)
);

CREATE TABLE LOAN_LIMITS(
    USER_ID     INT             NOT NULL  PRIMARY KEY,
    CURR_LOAN   DECIMAL(12,2)   NOT NULL  CHECK(CURR_LOAN >= 0),      
    ALLOWED_CAP DECIMAL(12,2)   NOT NULL DEFAULT 10000000.00,

    CHECK (CURR_LOAN <= ALLOWED_CAP),

    CONSTRAINT FK_LOANLIMITS_USERID
        FOREIGN KEY(USER_ID)
        REFERENCES USER(USER_ID)
);

CREATE TABLE REQUEST(
    REQUEST_ID      INT         NOT NULL  AUTO_INCREMENT  PRIMARY KEY,
    USER_ID         INT         NOT NULL,  
    REQUEST_CODE    INT         NOT NULL,
    REQUEST_DATE    DATETIME    NOT NULL,
    STATUS          VARCHAR(50) NOT NULL,

    CONSTRAINT FK_REQUEST_USERID
        FOREIGN KEY(USER_ID)
        REFERENCES USER(USER_ID),

    CONSTRAINT FK_REQUEST_REQUESTCODE
        FOREIGN KEY(REQUEST_CODE)
        REFERENCES REQUEST_TYPE(REQUEST_CODE)

);

CREATE TABLE TRANSACTION(
    TRANS_ID        INT             NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    TRANS_CODE      INT             NOT NULL,
    AC_NO           VARCHAR(20)     NOT NULL,
    TRANS_TYPE      VARCHAR(2)      NOT NULL,
    TRANS_DATE      DATETIME        NOT NULL,
    AMT             DECIMAL(12,2)   NOT NULL,
    DESCP           VARCHAR(255)    NOT NULL,

    CONSTRAINT FK_TRANSACTION_TRANSCODE
        FOREIGN KEY(TRANS_CODE)
        REFERENCES TRANSACTION_CODE(TRANS_CODE),

    CONSTRAINT FK_TRANSACTION_ACNO
        FOREIGN KEY(AC_NO)
        REFERENCES ACCOUNT(AC_NO)
);

CREATE TABLE NOTIFICATION(
    NOTIFICATION_ID     INT             NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    USER_ID             INT             NOT NULL,
    MESSAGE             VARCHAR(255)    NOT NULL,
    NOTIFICATION_DATE   DATETIME        NOT NULL,
    STATUS              VARCHAR(20)     NOT NULL,

    CONSTRAINT FK_NOTIFICATION_USERID
        FOREIGN KEY(USER_ID)
        REFERENCES USER(USER_ID)
);

CREATE TABLE AUTHENTICATION_LOG(
    LOG_ID      INT             NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    USER_ID     INT             NOT NULL,
    BOOTH_ID    INT             NOT NULL,
    LOGIN_TIME  DATETIME        NOT NULL,
    LOGOUT_TIME DATETIME        NULL,
    IMG_SOURCE  VARCHAR(255)    NOT NULL,
    STATUS      VARCHAR(20)     NOT NULL,

    CONSTRAINT FK_AUTHENTICATIONLOG_USERID
        FOREIGN KEY(USER_ID)
        REFERENCES USER(USER_ID),

    CONSTRAINT FK_AUTHENTICATIONLOG_BOOTHID
        FOREIGN KEY(BOOTH_ID)
        REFERENCES BOOTH(BOOTH_ID)

);


CREATE TABLE AUDIT_LOG(
    LOG_ID              INT         NOT NULL  PRIMARY KEY  AUTO_INCREMENT,
    USER_ID             INT         NOT NULL,
    ACTION              VARCHAR(50) NOT NULL,
    AFFECTED_USER_ID    INT         NOT NULL,
    DATE                DATETIME    NOT NULL,

    CONSTRAINT FK_AUDITLOG_USERID
        FOREIGN KEY(USER_ID)
        REFERENCES USER(USER_ID),

    CONSTRAINT FK_AUDITLOG_AFFECTEDUSERID
        FOREIGN KEY(AFFECTED_USER_ID)
        REFERENCES USER(USER_ID)
);